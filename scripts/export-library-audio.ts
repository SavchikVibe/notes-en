import { writeFileSync } from 'node:fs'
import { readings } from '../src/content/readings.ts'

const source = readings.map((reading) => ({
  id: reading.id,
  voice: reading.level === 'A1' || reading.level === 'A2' ? 'en-US-AriaNeural' : 'en-US-AvaNeural',
  rate: reading.level === 'A1' ? '-6%' : reading.level === 'A2' ? '-4%' : '-3%',
  text: reading.paragraphs.join('\n\n'),
}))

writeFileSync(
  'scripts/library-audio.json',
  `${JSON.stringify(source, null, 2)}\n`,
  'utf8',
)

const lines = readings.map(
  (reading) => `  '${reading.id}': 'audio/readings/${reading.id}.mp3',`,
)
const map = `// Generated by scripts/export-library-audio.ts. Do not edit by hand.
export const readingAudio: Record<string, string> = {
${lines.join('\n')}
}
`
writeFileSync('src/content/reading-audio.ts', map, 'utf8')
console.log(`Exported ${readings.length} readings.`)
